export function getSymbolName(symbol: string): string | undefined {
  return SYMBOL_META[symbol.toUpperCase()]?.name;
}
export function getCryptoIconUrl(symbol: string): string | undefined {
  return SYMBOL_META[symbol.toUpperCase()]?.icon;
}
export function categoriesOf(symbol: string): SymbolCategory[] {
  return SYMBOL_META[symbol.toUpperCase()]?.categories ?? [];
}
export function hasCategory(symbol: string, cat: SymbolCategory): boolean {
  return categoriesOf(symbol).includes(cat);
}

/** Registro proactivo de símbolos vistos sin metadata (ej. nuevos del trending). */
const seenUnmapped = new Set<string>();
export function noteIfUnmapped(symbol: string): void {
  const k = symbol.toUpperCase();
  if (!SYMBOL_META[k] && !seenUnmapped.has(k)) {
    seenUnmapped.add(k);
    if (typeof console !== "undefined") console.warn(`[symbol_meta] sin metadata: ${k}`);
  }
}
export function getUnmappedSeen(): string[] { return [...seenUnmapped]; }
